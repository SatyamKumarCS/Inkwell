// Creates apps/api/.dev.vars (git-ignored) for `wrangler dev` against the Firebase emulators, with a
// throwaway RSA key generated on this machine. Never used in production; real secrets go through
// `wrangler secret put`.
import { generateKeyPairSync } from 'node:crypto';
import { existsSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const target = fileURLToPath(new URL('../.dev.vars', import.meta.url));
if (existsSync(target)) process.exit(0);

const { privateKey } = generateKeyPairSync('rsa', { modulusLength: 2048 });
const serviceAccount = {
  type: 'service_account',
  project_id: 'demo-inkwell',
  private_key_id: 'dev-only',
  private_key: privateKey.export({ type: 'pkcs8', format: 'pem' }).toString(),
  client_email: 'inkwell-api@demo-inkwell.iam.gserviceaccount.com',
};

writeFileSync(
  target,
  [
    '# Local development only (git-ignored). Generated by scripts/ensure-dev-vars.mjs.',
    'FIREBASE_PROJECT_ID=demo-inkwell',
    'FIRESTORE_EMULATOR_HOST=127.0.0.1:8080',
    'FIREBASE_AUTH_EMULATOR_HOST=127.0.0.1:9099',
    'OTP_PEPPER=dev-only-pepper-not-for-production',
    'RESEND_API_KEY=unused-in-dev',
    `GOOGLE_SERVICE_ACCOUNT='${JSON.stringify(serviceAccount)}'`,
    '',
  ].join('\n'),
  { mode: 0o600 },
);
console.log('Created apps/api/.dev.vars (dev-only emulator settings and a throwaway key).');
